def characters_by_rank(rank):
    """Возвращает список персонажей указанного ранга."""
    return [c for c in CHARACTERS if c["rank"] == rank]


def get_character(name):
    """Находит персонажа по имени."""
    for c in CHARACTERS:
        if c["name"] == name:
            return c
    return None
